export const getQuiz = (id) => {
  if (id === "random") return generateRandomQuiz();
  return quizzes.find((q) => q.id === id);
};

export function generateRandomQuiz() {
  const allQuestions = quizzes.flatMap((q) =>
    q.questions.map((question) => ({ ...question, source: q.title }))
  );
  const shuffled = [...allQuestions].sort(() => Math.random() - 0.5);
  const selected = shuffled.slice(0, 15);
  return {
    id: "random",
    title: "Quiz Aléatoire",
    icon: "🎲",
    questions: selected,
  };
}
